package org.graalnix.lint.test;

import static org.assertj.core.api.Assertions.assertThat;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import org.graalnix.lint.Rule;
import org.junit.jupiter.api.Test;

/**
 * Generates web/playground/examples.js from the cases: each rule's case, for the playground's rule selector. When the
 * file is out of date, the test rewrites it and fails, so that the new version gets committed.
 */
class PlaygroundExamplesTest {
    private static final Path PLAYGROUND = Path.of("web/playground");

    private static final Path GENERATED = PLAYGROUND.resolve("examples.js");

    @Test
    void examplesAreUpToDate() throws IOException {
        assumeTrue(
                Files.isDirectory(PLAYGROUND),
                "no web/playground/ in " + Path.of("").toAbsolutePath());
        String js = generate();
        String committed = Files.exists(GENERATED) ? Files.readString(GENERATED, StandardCharsets.UTF_8) : "";
        if (!js.equals(committed)) Files.writeString(GENERATED, js, StandardCharsets.UTF_8);
        assertThat(committed)
                .as(GENERATED + " was out of date and has been rewritten")
                .isEqualTo(js);
    }

    private static String generate() throws IOException {
        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by PlaygroundExamplesTest from lint/src/test/java/cases/: do not edit.\n");
        sb.append("const examples = {\n");
        for (Rule r : Rule.values()) {
            if (r == Rule.SYNTAX_ERROR) continue;
            sb.append("  ")
                    .append(quote(r.id()))
                    .append(": ")
                    .append(quote(LintTest.read(LintTest.CASES.resolve(r.id() + ".nix"))))
                    .append(",\n");
        }
        return sb.append("};\n").toString();
    }

    private static String quote(String s) {
        StringBuilder sb = new StringBuilder(s.length() + 2).append('"');
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            switch (c) {
                case '"' -> sb.append("\\\"");
                case '\\' -> sb.append("\\\\");
                case '\n' -> sb.append("\\n");
                case '\t' -> sb.append("\\t");
                default -> {
                    if (c < 0x20) sb.append(String.format("\\u%04x", (int) c));
                    else sb.append(c);
                }
            }
        }
        return sb.append('"').toString();
    }
}
