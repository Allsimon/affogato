package org.affogato.tools;

import java.io.IOException;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.SequencedMap;
import org.affogato.lint.Rule;

/** web/playground/examples.js: each rule's test case, for the playground's rule selector. */
final class PlaygroundExamples {
    private PlaygroundExamples() {}

    static Generate.Output generate(Path root) throws IOException {
        Path cases = root.resolve(LintRules.CASES);
        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by tools/ (playground-examples) from lint/src/test/java/cases/: do not edit.\n");
        sb.append("export const examples = {\n");
        for (Rule r : Rule.values()) {
            if (r == Rule.SYNTAX_ERROR) continue;
            sb.append("  ")
                    .append(quote(r.id()))
                    .append(": ")
                    .append(quote(Generate.read(cases.resolve(r.id() + ".nix"))))
                    .append(",\n");
        }
        SequencedMap<Path, String> files = new LinkedHashMap<>();
        files.put(Path.of("web", "playground", "examples.js"), sb.append("};\n").toString());
        return new Generate.Output(files);
    }

    private static String quote(String s) {
        StringBuilder sb = new StringBuilder(s.length() + 2).append('"');
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            switch (c) {
                case '"' -> sb.append("\\\"");
                case '\\' -> sb.append("\\\\");
                case '\n' -> sb.append("\\n");
                case '\t' -> sb.append("\\t");
                default -> {
                    if (c < 0x20) sb.append(String.format("\\u%04x", (int) c));
                    else sb.append(c);
                }
            }
        }
        return sb.append('"').toString();
    }
}
