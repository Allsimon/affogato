package org.affogato.tools.generator;

import java.io.IOException;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.SequencedMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/** format/_versions.adoc, included by the README: the nixfmt of vendir.yml and the nixpkgs of flake.lock. */
final class Versions {
    private static final String NIXFMT = "url: https://github.com/NixOS/nixfmt\\s+ref: (\\S+)";
    private static final String NIXPKGS = "\"nixpkgs\":\\s*\\{\\s*\"locked\":\\s*\\{[^}]*\"rev\":\\s*\"(\\w+)\"";

    private Versions() {}

    static Generate.Output generate(Path root) throws IOException {
        String nixfmt = find(root.resolve("vendir.yml"), NIXFMT);
        String nixpkgs = find(root.resolve("flake.lock"), NIXPKGS);
        SequencedMap<Path, String> files = new LinkedHashMap<>();
        files.put(Path.of("format", "_versions.adoc"), """
            // Generated by tools/generator (versions) from vendir.yml and flake.lock; do not edit.
            * nixfmt version: https://github.com/NixOS/nixfmt/tree/%1$s[%1$s]
            * nixpkgs version: https://github.com/NixOS/nixpkgs/tree/%2$s[%2$s]
            """.formatted(nixfmt, nixpkgs));
        return new Generate.Output(files);
    }

    private static String find(Path file, String regex) throws IOException {
        Matcher matcher = Pattern.compile(regex).matcher(Generate.read(file));
        if (!matcher.find()) throw new IllegalStateException(file + " does not match " + regex);
        return matcher.group(1);
    }
}
