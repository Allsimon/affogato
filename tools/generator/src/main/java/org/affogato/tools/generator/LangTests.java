package org.affogato.tools.generator;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.SequencedMap;
import java.util.Set;
import java.util.stream.Stream;

/** docs/_lang-tests.adoc: how many of each vendored language suite's tests LangTest runs and how many pass. */
final class LangTests {
    private static final Path TESTS = Path.of("language", "src", "test", "java");

    private LangTests() {}

    static Generate.Output generate(Path root) throws IOException {
        Path tests = root.resolve(TESTS);
        Set<String> skip = Set.copyOf(Files.readAllLines(tests.resolve("lang-skip.txt")).stream()
                .map(line -> line.replaceAll("#.*", "").trim())
                .filter(line -> !line.isEmpty())
                .toList());
        StringBuilder text = new StringBuilder(
                "// Generated by tools/generator (lang-tests) from the test data and lang-skip.txt; do not edit.\n");
        for (String suite : List.of("lang", "tvix")) {
            Path dir = tests.resolve(suite);
            List<Path> all = new ArrayList<>();
            for (Path test : tests(dir, "eval-okay-")) {
                if (!Files.exists(sibling(test, ".exp.xml")) && !Files.exists(sibling(test, ".exp-disabled")))
                    all.add(test);
            }
            all.addAll(tests(dir, "eval-fail-"));
            all.addAll(tests(dir, "parse-okay-"));
            all.addAll(tests(dir, "parse-fail-"));
            String prefix = suite.equals("tvix") ? "tvix/" : "";
            long skipped = all.stream()
                    .filter(test -> skip.contains(prefix + name(test)))
                    .count();
            text.append(":%s-tests: %d\n:%s-passed: %d\n".formatted(suite, all.size(), suite, all.size() - skipped));
        }
        SequencedMap<Path, String> files = new LinkedHashMap<>();
        files.put(Path.of("docs", "_lang-tests.adoc"), text.toString());
        return new Generate.Output(files);
    }

    private static List<Path> tests(Path dir, String prefix) throws IOException {
        try (Stream<Path> files = Files.list(dir)) {
            return files.filter(file -> file.getFileName().toString().startsWith(prefix)
                            && file.toString().endsWith(".nix"))
                    .sorted()
                    .toList();
        }
    }

    private static Path sibling(Path test, String suffix) {
        return test.resolveSibling(name(test) + suffix);
    }

    private static String name(Path test) {
        String file = test.getFileName().toString();
        return file.substring(0, file.length() - 4);
    }
}
