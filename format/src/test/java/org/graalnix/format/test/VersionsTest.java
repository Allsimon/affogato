package org.graalnix.format.test;

import static org.assertj.core.api.Assertions.assertThat;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.junit.jupiter.api.Test;

/**
 * Writes format/_versions.adoc, included by the README, from the nixfmt of vendir.yml and the nixpkgs of flake.lock.
 * When it is out of date, the test rewrites it and fails, so that the new version gets committed.
 */
class VersionsTest {
    private static final Path VERSIONS = Path.of("format", "_versions.adoc");
    private static final String NIXFMT = "url: https://github.com/NixOS/nixfmt\\s+ref: (\\S+)";
    private static final String NIXPKGS = "\"nixpkgs\":\\s*\\{\\s*\"locked\":\\s*\\{[^}]*\"rev\":\\s*\"(\\w+)\"";

    @Test
    void versionsAreUpToDate() throws IOException {
        assumeTrue(
                Files.exists(Path.of("flake.lock")),
                "no flake.lock in " + Path.of("").toAbsolutePath());
        String nixfmt = find(read(Path.of("vendir.yml")), NIXFMT);
        String nixpkgs = find(read(Path.of("flake.lock")), NIXPKGS);
        String expected = """
            // Generated by VersionsTest from vendir.yml and flake.lock; do not edit.
            * nixfmt version: https://github.com/NixOS/nixfmt/tree/%1$s[%1$s]
            * nixpkgs version: https://github.com/NixOS/nixpkgs/tree/%2$s[%2$s]
            """.formatted(nixfmt, nixpkgs);

        String committed = Files.exists(VERSIONS) ? read(VERSIONS) : "";
        if (!committed.equals(expected)) Files.writeString(VERSIONS, expected, StandardCharsets.UTF_8);
        assertThat(committed).as("out of date and rewritten: " + VERSIONS).isEqualTo(expected);
    }

    private static String read(Path p) throws IOException {
        return Files.readString(p, StandardCharsets.UTF_8);
    }

    private static String find(String text, String regex) {
        Matcher m = Pattern.compile(regex).matcher(text);
        assertThat(m.find()).as(regex).isTrue();
        return m.group(1);
    }
}
